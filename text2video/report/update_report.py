"""
This script has the goal of updating the results report with additional results generated by other scripts.

Video:
- Update report with FVD metric results

"""
import argparse
import pandas as pd
import pickle

from text2video.utils.file_utils import load_json


def parse_args():
    """Argument parsing function"""
    parser = argparse.ArgumentParser(description="Update the report with metrics")
    parser.add_argument(
        "--report_path", type=str, help="Path to the markdown file of the report")
    parser.add_argument(
        "--result_to_add", type=str, default=None,
        help="Path to the result (.pickle or .json) to add that contains a dictionary")
    parser.add_argument(
        "--title", type=str, default=None,
        help="Title to be added in the report for the section to be added")
    args = parser.parse_args()

    return args


def main():
    """Main function of the evaluation/inference script"""
    args = parse_args()

    data_result = None
    result_to_add_file = args.result_to_add
    if result_to_add_file.endswith(".json"):
        data_result = load_json(result_to_add_file)
    else:
        with open(result_to_add_file, "rb") as current_file:
            data_result = pickle.load(current_file)

    # Generate report on Markdown
    df = pd.DataFrame(data_result.items(), columns=['Metric', 'Value'])
    df['Value'] = df['Value'].map('{:,.4f}'.format)
    markdown_table = df.to_markdown(index=False)
    print(markdown_table)

    title = f"- {args.title}" if args.title is not None else ""
    print(title)

    markdown_string = f'''

## FVD I3D model {title}

{markdown_table}

'''
    print(f"\nWriting additional result to <{args.report_path}>")
    with open(args.report_path, "a") as f:
        f.write(markdown_string)
    print("Finished updating report.")


if __name__ == '__main__':
    main()
